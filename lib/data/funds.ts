const FUND_INDEX = new Map(FUNDS.map((f) => [f.id, f]))

export function getFund(id: string): Fund {
  const fund = FUND_INDEX.get(id)
  if (!fund) throw new Error(`Unknown fund id: ${id}`)
  return fund
}

/** The 22 Phase 3 candidates plus the (unscored) Nifty 50 tracker. */
export const RESEARCH_UNIVERSE = FUNDS.filter(
  (f) => f.phase3Score !== null || f.id === "nifty50"
)

/** Instruments a user can add in the builder. */
export const BUILDER_UNIVERSE = FUNDS.filter(
  (f) => f.id !== "cash-pending" && f.id !== "absl-liquid"
)

export type SubstitutionGroup = "equity" | "sharia" | "fixed-income" | "liquidity" | "base-tier"

export function substitutionGroup(f: Fund): SubstitutionGroup {
  if (f.sleeve === "sharia") return "sharia"
  if (f.assetClass === "equity") return "equity"
  return f.assetClass
}

export function isShariaScreened(f: Fund) {
  return f.shariaStatus === "supervised" || f.shariaStatus === "unverified"
}

/** Risk band derived from category only — the proposal does not reproduce SEBI riskometer levels. */
export function riskBand(f: Fund): "Low" | "Low–moderate" | "Moderate" | "High" | "Very high" {
  if (f.assetClass === "liquidity" || f.assetClass === "base-tier") return "Low"
  if (f.category === "Gilt") return "Moderate"
  if (f.assetClass === "fixed-income") return "Low–moderate"
  if (["Mid Cap", "Large & Mid Cap", "Focused", "Multi Cap"].includes(f.category)) return "Very high"
  if (f.category === "Sharia equity" && (f.midSmallPct ?? 0) > 40) return "Very high"
  return "High"
}
