/**
 * Fund universe for the client trust's portfolio.
 *
 * Source of truth: the "Investment & Portfolio Restructuring Proposal"
 * (September 2026). Every attribute below is taken from that document; where
 * the document is silent the field is `null` and the UI renders it as
 * "Not available". Nothing here is estimated unless `provenance` says so.
 */

export type AssetClass = "equity" | "fixed-income" | "liquidity" | "base-tier"

export type Sleeve =
  | "core"
  | "passive"
  | "satellite"
  | "sharia"
  | "fixed-income"
  | "liquidity"
  | "base-tier"

export type RegTier = "c619" | "base"

export type ResearchStatus = "selected" | "bench" | "rejected" | "exit" | "instrument"

export type ShariaStatus =
  | "supervised" // Shariah-screened with a named supervisory board
  | "unverified" // Shariah-screened, supervisor / policy not confirmed
  | "not-certified" // "ethical" mandate, not certified Sharia
  | "conventional"

export type ComponentKey =
  | "returnQuality"
  | "risk"
  | "diversification"
  | "costEfficiency"
  | "liquidity"
  | "governance"
  | "legalCompliance"
  | "shariaCompatibility"

export const COMPONENT_LABELS: Record<ComponentKey, string> = {
  returnQuality: "Return quality",
  risk: "Risk",
  diversification: "Diversification",
  costEfficiency: "Cost efficiency",
  liquidity: "Liquidity",
  governance: "Governance",
  legalCompliance: "Legal compliance",
  shariaCompatibility: "Sharia compatibility",
}

export interface Fund {
  id: string
  name: string
  shortName: string
  amc: string
  category: string
  assetClass: AssetClass
  sleeve: Sleeve
  regTier: RegTier
  /** Circular 619 clause (Gate 1) or base-tier basis. */
  gate1Basis: string
  /** Income-tax Act s.11(5) / Rule 17C basis (Gate 2). */
  gate2Basis: string
  phase3Score: number | null
  scoreNote?: string
  researchStatus: ResearchStatus
  /** Recommendation / role as printed in Appendix D or Section 10. */
  roleLabel: string
  /** 3-year Jensen alpha vs the fund's own benchmark, percentage points (§14.2). */
  alpha: number | null
  /** 3-year beta. Debt-fund betas are against debt benchmarks (§14.2 note **). */
  beta: number | null
  betaBenchmark: "equity" | "debt" | null
  /** True where the PDF assigns alpha/beta by convention rather than measurement. */
  alphaBetaAssumed?: boolean
  alphaBetaNote?: string
  /** Only the component scores the proposal actually discloses. */
  components: Partial<Record<ComponentKey, number>>
  /** Approximate modified duration in years. */
  duration: number | null
  durationNote?: string
  durationEstimated?: boolean
  /** Credit quality, % of fund. Only what the proposal discloses. */
  credit: {
    aaaSovereign: number | null // combined AAA / sovereign / A1+ as printed
    belowAAA: number | null
    note: string
  } | null
  foreignPct: number | null
  foreignNote?: string
  midSmallPct: number | null
  midSmallNote?: string
  aumCr: number | null
  shariaStatus: ShariaStatus
  shariaNote?: string
  monitoring: string
  rationale: string
  flags: string[]
  source: string
}

